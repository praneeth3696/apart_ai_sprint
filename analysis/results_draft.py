"""
results_draft.py

Emits `analysis/RESULTS_DRAFT.md` — the Results section, with every number
read out of `analysis/e1_stats.json` rather than typed.

WHY THIS IS GENERATED AND NOT WRITTEN
-------------------------------------
The numbers are still moving: E1 widens as quota allows, E3 is mid-run, and
Google's daily caps reset overnight. A hand-typed Results section starts
drifting from the data the moment the next run lands, and the drift is silent
— nobody re-reads a paragraph they already wrote. Regenerating is free, so the
prose is regenerated.

The prose here is a DRAFT for a human to cut and sharpen, not final copy. What
it guarantees is that every figure in it matches `e1_stats.json` at the moment
it ran, and that the caveats which must not be dropped are present by
construction:

  - n, stated everywhere, because n is 10-36 and the intervals are wide;
  - the census/uniform distinction, never pooled;
  - `sev_threshold` named as an ORACLE every time it appears;
  - non-observations excluded from denominators and reported separately;
  - the blind-check labeller disclosure;
  - the pre-registered null for E3.

Usage:
    python analysis/stats.py --eai
    python analysis/results_draft.py
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
from datetime import datetime, timezone

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "analysis"))
sys.path.insert(0, str(REPO / "harness"))
sys.path.insert(0, str(REPO / "corpus"))

import figures as F      # noqa: E402  (arm_of / short / e0_points)
import stats as S        # noqa: E402  (wilson, so every CI in the paper
                         #              comes from one function)

STATS = REPO / "analysis" / "e1_stats.json"
E0 = REPO / "analysis" / "e0_baselines.json"
BLIND = REPO / "analysis" / "blind_check_result.json"
OUT = REPO / "analysis" / "RESULTS_DRAFT.md"


def pct(d: dict) -> str:
    if not d or not d.get("n"):
        return "—"
    return (f"{d['k']}/{d['n']} ({d['rate']:.0%}, CI95 "
            f"{d['ci95'][0]:.0%}–{d['ci95'][1]:.0%})")


def short_pct(d: dict) -> str:
    if not d or not d.get("n"):
        return "—"
    return f"{d['k']}/{d['n']} = {d['rate']:.0%}"


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--stats", default=str(STATS))
    p.add_argument("--out", default=str(OUT))
    args = p.parse_args(argv)

    st = json.loads(pathlib.Path(args.stats).read_text(encoding="utf-8"))
    per = st["per_model"]
    e0 = json.loads(E0.read_text(encoding="utf-8"))
    blind = json.loads(BLIND.read_text(encoding="utf-8")) if BLIND.is_file() else {}

    # pooled, sliced correctly
    m_k = sum(s["milestone_hit_rate"]["k"] for s in per.values())
    m_n = sum(s["milestone_hit_rate"]["n"] for s in per.values())
    b_k = sum(s["benign_false_page_rate"]["k"] for s in per.values())
    b_n = sum(s["benign_false_page_rate"]["n"] for s in per.values())

    e0pts = {p["label"]: p for p in F.e0_points()}
    L: list[str] = []
    A = L.append

    A("<!-- GENERATED by analysis/results_draft.py — do not hand-edit.")
    A("     Re-run it after every experiment run; every number here is read")
    A(f"     from {pathlib.Path(args.stats).name}. -->")
    A("")
    A("# Results — DRAFT")
    A("")
    A(f"Generated {datetime.now(timezone.utc).isoformat(timespec='seconds')} "
      f"from `{st['source']}` ({st['n_records_after_dedupe']} settled records).")
    A("")
    A("## R0. What the denominators are")
    A("")
    A("Two attack-stream populations are reported and **never pooled**:")
    A("")
    A("- the **milestone census** — all 12 attack windows carrying a sourced")
    A("  milestone. A census, not a sample.")
    A("- the **uniform sample** — evenly spaced windows on a nested ladder,")
    A("  the like-for-like comparison to the benign control.")
    A("")
    A("Pooling them biases the attack page rate upward, because the census")
    A("over-represents high-severity windows by construction.")
    A("")
    A(f"Excluded from every denominator: `{'`, `'.join(st['denominators']['excluded'])}`. "
      "These record that we")
    A("could not buy the observation, not that a model did anything "
      "(RUBRIC.md §0).")
    A("")

    A("## R1. The control is usable")
    A("")
    if blind:
        # No CI is stored in the result file; recompute it with the same
        # Wilson function E0 and E1 use, so all three agree.
        lo, hi = S.wilson(blind["n_correct"], blind["n_windows"])
        A(f"The benign stream is not trivially separable from the attack "
          f"stream: **{blind['n_correct']}/{blind['n_windows']} "
          f"({blind['accuracy']:.0%})**, CI95 {lo:.1%}–{hi:.1%}, "
          f"p = {blind['p_value_vs_chance_one_sided']:.3f} against chance —")
        A(f"against a pre-registered failure threshold of "
          f"{blind['threshold']:.0%}. Verdict: **{blind['verdict']}**.")
        A(f"Attack recall {blind['attack_recall']:.0%}, benign recall "
          f"{blind['benign_recall']:.0%} — no label bias. The false-page")
        A("denominator is therefore defensible.")
        A("")
        lab = blind.get("labeller", {})
        if lab:
            A(f"> **Disclosure — the labeller was not a human.** "
              f"{lab.get('who', 'unknown')}.")
            A(f"> Inputs read: {lab.get('inputs_read', 'unknown')}.")
            A(">")
            A("> " + lab.get("caveat", "").replace("\n", " "))
        if blind.get("caveat"):
            A(">")
            A("> **Power.** " + blind["caveat"].replace("\n", " "))
    else:
        A("_(blind_check_result.json not found)_")
    A("")

    A("## R2. Rule baselines (E0) — no API calls")
    A("")
    A("| detector | milestone hit | benign false-page | first page |")
    A("|---|---|---|---|")
    for label, pt in e0pts.items():
        det = e0["attack"]["detectors"].get(
            label.replace(" (ORACLE)", "(ORACLE)"), {})
        eai = det.get("eai") or {}
        A(f"| `{label}` | {short_pct(pt['hit'])} | {short_pct(pt['fp'])} | "
          f"action #{eai.get('action_idx', '—')} |")
    A("")
    A("`sev_threshold` reads ground-truth severity. **It is an ORACLE — an upper")
    A("bound on any detector that already knew the answer — and must never be")
    A("described as something a defender could deploy.** The only deployable")
    vs = e0pts.get("volume_spike")
    if vs:
        A(f"rule that keeps a low false-page rate, `volume_spike`, catches "
          f"**{vs['hit']['k']} of {vs['hit']['n']}** milestone windows.")
    A("")

    A("## R3. Models (E1)")
    A("")
    A("| model | provider | milestone hit (census) | benign false-page (uniform) | separation | Fisher p |")
    A("|---|---|---|---|---|---|")
    for model, s in per.items():
        sep = f"{s['separation']:+.0%}" if s["separation"] is not None else "—"
        pv = (f"{s['fisher_milestone_vs_benign']:.3f}"
              if s["fisher_milestone_vs_benign"] is not None else "—")
        A(f"| `{F.short(model)}` | {s.get('provider') or '—'} | "
          f"{pct(s['milestone_hit_rate'])} | {pct(s['benign_false_page_rate'])} | "
          f"{sep} | {pv} |")
    A("")
    if m_n and b_n:
        A(f"**Pooled across models: milestone {m_k}/{m_n} ({m_k / m_n:.0%}), "
          f"benign false-page {b_k}/{b_n} ({b_k / b_n:.0%}).**")
        A("")
        A("Models catch the incident and also page on a large fraction of")
        A("innocent traffic. This reproduces on frontier models the E0 result")
        A("that the two deployable rule detectors cannot separate the streams.")
    A("")
    sig = [m for m, s in per.items()
           if (s["fisher_milestone_vs_benign"] or 1) < 0.05]
    A(f"**Significance, stated plainly: {len(sig)} of {len(per)} models reach "
      f"p < 0.05** on milestone-vs-benign separation")
    A("at this sample size" + (f" ({', '.join(F.short(m) for m in sig)})."
                               if sig else " — none."))
    A("Per-model n is 4–36 and the intervals overlap heavily. The reportable")
    A("claim is the **gradient across models**, not any individual model's")
    A("significance. Widening the sample is the single highest-value")
    A("follow-up, and the sampling ladder makes it additive.")
    A("")

    A("## R4. Escalation latency (EAI) — reported, not headlined")
    A("")
    A("Every E0 detector fires at action #15–51 of 17,613, roughly 10,400")
    A(f"actions before the escalation point (#{e0['attack']['reference_lines']['escalation_point']['action_idx']:,}), "
      "on filler that is")
    A("byte-identical in both streams. On this corpus a first page measures")
    A("trigger-happiness rather than detection. EAI is reported for")
    A("completeness (Figure 2); the headline pair is R3's.")
    A("")
    if st.get("eai"):
        A("| model | EAI action | lead to escalation point |")
        A("|---|---|---|")
        for model, row in st["eai"].items():
            lead = row.get("lead_h_to_escalation_point")
            A(f"| `{F.short(model)}` | {row['eai_action_idx'] or 'never'} | "
              f"{f'{lead:+.1f} h' if lead is not None else '—'} |")
        A("")

    e3 = st.get("e3", {}).get("per_model", {})
    A("## R5. Incoherence (E3)")
    A("")
    if e3:
        A("| model | incoherence rate | escalated | refused to assist | McNemar p |")
        A("|---|---|---|---|---|")
        for model, s in e3.items():
            A(f"| `{F.short(model)}` | {pct(s['incoherence_rate'])} | "
              f"{short_pct(s['escalated'])} | {short_pct(s['refused_to_assist'])} | "
              f"{s['mcnemar_escalate_vs_assist']['p_exact']:.3f} |")
        A("")
        tot_i = sum(s["incoherence_rate"]["k"] for s in e3.values())
        tot_n = sum(s["incoherence_rate"]["n"] for s in e3.values())
        A(f"Pooled: **{tot_i}/{tot_n}** scoreable 2×2 cells are INCOHERENT.")
        A("")
        if tot_i == 0:
            A("**This is the pre-registered null, and it is a result, not a failed")
            A("experiment.** PLAN.md §4 pre-registers that a coherent model shows")
            A("incoherence ≈ 0; PREREGISTRATION branch H-D commits in advance to")
            A("E0+E1 carrying the paper in that case. No model in this roster")
            A("refused to analyse evidence it had just declined to escalate.")
        else:
            A("Any rate materially above zero is the finding — a model that will")
            A("neither wake anyone nor help analyse the same bytes.")
        A("")
        A("Cells outside the 2×2 (`filtered-both`, `unscoreable-*`) are excluded")
        A("from the denominator and reported separately: in each the model made")
        A("no judgment we could score.")
    else:
        A("_(E3 has not been scored yet — run `harness/e3_incoherence.py`, then")
        A("`analysis/stats.py`.)_")
    A("")

    A("## R6. Cost")
    A("")
    A("**$0.00.** Every call was made on a free tier. The constraint that")
    A("shaped the study was throughput, not price: per-model daily caps of")
    A("10–31 requests on Google AI Studio and 1,000 on Groq, measured rather")
    A("than assumed (`harness/PROVIDERS.md`).")
    A("")

    pathlib.Path(args.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {pathlib.Path(args.out).relative_to(REPO)}  ({len(L)} lines)")
    if not sig:
        print("  NOTE: no model reaches p<0.05 — the draft says so explicitly.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
